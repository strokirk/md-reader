// Triggered by: three-term search correctly highlighted matches in
// paragraphs, but never in headings (see LEARNINGS.md #9) — no error, no
// console output, just a plain heading with matching text and no colour.
//
// This script is what actually found the bug: it drives a real search and
// reader-open flow, then reaches into the live `CSS.highlights` registry
// (something no unit test or type checker can inspect) and inspects the
// Range objects backing a heading's highlight directly — confirming they
// were being registered with the wrong (collapsed / wrong-container)
// boundaries. Kept as a worked example of that inspection technique for
// any future CSS Custom Highlight API bug; the fix itself lives in
// src/ui/render.ts (BlockList.build()).
//
// Usage: node scripts/diagnose-heading-highlight.mjs <corpus-dir> [url]
// (requires `npm run build && npm run preview` running at `url`, and a
// corpus generated by scripts/gen-test-corpus.mjs)
import { chromium } from "playwright";
import { readdirSync, statSync } from "node:fs";
import { join } from "node:path";

const [corpusDir, url = "http://localhost:4173/"] = process.argv.slice(2);
if (!corpusDir) {
  console.error("usage: node scripts/diagnose-heading-highlight.mjs <corpus-dir> [url]");
  process.exit(1);
}
function walk(dir, out = []) {
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

const browser = await chromium.launch(
  process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {},
);
const page = await (
  await browser.newContext({
    viewport: { width: 390, height: 844 },
    isMobile: true,
    hasTouch: true,
  })
).newPage();
page.on("pageerror", (e) => console.log("pageerror:", e.message));
try {
  await page.goto(url);
  await page.waitForSelector(".library-view");
  const [chooser] = await Promise.all([
    page.waitForEvent("filechooser"),
    page.click("text=Add files"),
  ]);
  const files = walk(corpusDir);
  await chooser.setFiles(files);
  await page.waitForFunction(
    (n) => document.querySelectorAll(".book-row").length >= n,
    files.length,
    { timeout: 60000 },
  );

  await page.click('button[aria-label="Search"]');
  const terms = ["grapple", "fireball", "saving throw"];
  for (let i = 0; i < terms.length; i++) {
    if (i > 0) await page.click("text=Add term");
    await page.locator("input.term-input").nth(i).fill(terms[i]);
  }
  await page.keyboard.press("Enter");
  await page.waitForFunction(() => {
    const t = document.querySelector(".status")?.textContent ?? "";
    return /match/.test(t) && !/…/.test(t);
  });
  await page.locator(".group-blocks .hit").first().click();
  await page.waitForSelector(".reader-view:not([hidden])");
  await page.waitForTimeout(700);

  const info = await page.evaluate(() => {
    const heading = [...document.querySelectorAll(".blk-h")].find((h) =>
      h.textContent.includes("saving throw"),
    );
    if (!heading) return { found: false };
    const rangeSummary = (highlightName) =>
      [...(CSS.highlights.get(highlightName) ?? [])]
        .filter((r) => heading.contains(r.startContainer))
        .map((r) => ({ text: r.toString(), collapsed: r.collapsed, startOffset: r.startOffset }));
    return {
      found: true,
      headingText: heading.textContent.trim(),
      // Before the fix: empty (the Range was never correctly registered
      // against this now-connected node). After the fix: one entry with
      // text "saving throw" and collapsed:false.
      term2OnHeading: rangeSummary("term-2"),
    };
  });
  console.log(JSON.stringify(info, null, 2));
  console.log(
    info.found && info.term2OnHeading.length > 0
      ? "OK: heading highlight range present and non-collapsed."
      : "REGRESSION: heading highlight range missing — see LEARNINGS.md #9.",
  );
} finally {
  await browser.close();
}
